def needs_operator_line(err, product=None):
    return f"NEEDS OPERATOR: {err} — edit the file or run asf init --product {product or '<p>'}"


ITEM_FOLDERS = ('epics', 'features', 'stories', 'tasks', 'bugs', 'decisions', 'rules')


def _looks_like_record(path):
    """``path`` is a record itself: it carries ``index.json`` or one of the item folders. A
    product repo's cwd (code, no item folders, no index) is never mistaken for one; neither is
    an empty directory."""
    return (os.path.isfile(os.path.join(path, 'index.json'))
            or any(os.path.isdir(os.path.join(path, d)) for d in ITEM_FOLDERS))


def resolve_record(args, announce=print):
    """The record a record command runs against. ``--product`` given explicitly always wins:
    that product's ``backlog_dir`` is the record, even when the cwd happens to be a record too —
    a product repo's cwd is never mistaken for one. Otherwise, a cwd that already looks like a
    record (an ``index.json`` beside ``epics/``) is used as it stands — the ordinary way these
    tools are run, from inside the backlog checkout. Only when the cwd is *not* a record (it is
    a product's code repo, say) does ``$ASF_PRODUCT`` or ``config.yaml``'s ``default_product``
    stand in, so the command still resolves the right record instead of silently doing nothing
    to the cwd. Prints ``record: <path>`` as the first line, so the operator always sees which
    one ran — through ``announce`` (stdout; ``new`` and ``stale`` send it to stderr, their stdout
    being a value a script reads: the minted id, the ``--json`` table)."""
    from asf import env
    name = getattr(args, 'product', None)
    cwd = os.getcwd()
    if name is None and _looks_like_record(cwd):
        announce(f"record: {cwd}")
        return cwd
    if name is None:
        name = env.default_product_name()
    record = env.load_product(name).backlog_dir
    if not record:
        raise env.ConfigError(f"product {name!r} has no backlog_dir configured")
    announce(f"record: {record}")
    return record


def _announce_stderr(line):
    print(line, file=sys.stderr)


def _product_of(argv):
    argv = list(sys.argv[1:] if argv is None else argv)
    for i, a in enumerate(argv):
        if a == '--product' and i + 1 < len(argv):
            return argv[i + 1]
        if a.startswith('--product='):
            return a.split('=', 1)[1]
    return None


def line_buffered(*streams):
    """Flush each stream at every newline. A scheduled tick writes to a log file, where Python
    block-buffers: a tick running twenty minutes showed nothing of itself until it ended. A
    stream that cannot be reconfigured (a test's StringIO) is left alone."""
    for stream in streams:
        try:
            stream.reconfigure(line_buffering=True)
        except (AttributeError, ValueError, OSError):
            pass


def _utc_today():
    import datetime
    return datetime.datetime.now(datetime.timezone.utc).strftime('%Y-%m-%d')


def _published(cmd, args, record, message):
    """Run a console command that writes the record, then commit and push what it wrote
    (:func:`asf.record.publish.publish_changes`): the tick's clone resets to origin, so an edit
    left in the operator's checkout never reaches it. The tick calls these commands on its own
    clone directly, never through here, so its state commit stays its own."""
    from asf.record import publish
    before = publish.snapshot(record)
    rc = cmd(args, record)
    publish.publish_changes(record, before, message)
    return rc


def main(argv=None):
    from asf import env, tables
    line_buffered(sys.stdout, sys.stderr)  # before BoxStream wraps stdout, which passes lines on
    finish = tables.install()   # markdown tables are drawn as box tables on a console
    try:
        return _main(argv)
    except env.ConfigError as e:
        print(needs_operator_line(e, _product_of(argv)))
        return 2
    finally:
        finish()


def _main(argv=None):
    parser = build_parser()
    args = parser.parse_args(argv)
    root = os.getcwd()  # only `hook` (a runtime hook in the project) and `plugin` run on the cwd

    if args.command == 'new':
        from asf.record.new import cmd_new
        return cmd_new(args, resolve_record(args, announce=_announce_stderr))
    if args.command == 'inbox':
        from asf.groom.inbox import cmd_inbox
        return cmd_inbox(args, resolve_record(args, announce=_announce_stderr))
    if args.command == 'idea':
        from asf.idea.cli import cmd_idea
        return cmd_idea(args, resolve_record(args, announce=_announce_stderr))
    if args.command == 'set':
        from asf.record.setfield import cmd_set
        return _published(cmd_set, args, resolve_record(args, announce=_announce_stderr),
                          f"record: set {args.id}")
    if args.command == 'check':
        from asf.record.check import cmd_check
        return cmd_check(args, resolve_record(args))
    if args.command == 'index':
        from asf.record.index import cmd_index
        return cmd_index(args, resolve_record(args))
    if args.command == 'ingest':
        from asf.record.ingest import cmd_ingest
        return cmd_ingest(args, resolve_record(args))
    if args.command == 'migrate':
        from asf.tick.migrate import cmd_migrate
        return cmd_migrate(args, resolve_record(args))
    if args.command == 'groom':
        from asf.groom.groom import cmd_groom
        return _published(cmd_groom, args, resolve_record(args),
                          f"groom: {args.date or _utc_today()}" + (' --apply' if args.apply else ''))
    if args.command == 'stale':
        from asf.tick.stale import cmd_stale
        return cmd_stale(args, resolve_record(args, announce=_announce_stderr))  # stdout: the table / --json
    if args.command == 'file-bugs':
        from asf.tick.file_bugs import cmd_file_bugs
        return cmd_file_bugs(args, resolve_record(args))
    if args.command == 'rules':
        from asf.rules.rules import cmd_check as rules_cmd_check
        return rules_cmd_check(args, resolve_record(args))
    if args.command == 'evidence':
        from asf.evidence.evidence import main as evidence_main
        evidence_args = ['--json']
        if args.fresh:
            evidence_args.append('--fresh')
        if args.product:
            evidence_args += ['--product', args.product]
        return evidence_main(evidence_args)
    if args.command == 'harvest':
        from asf.harvest.harvest import main as harvest_main
        harvest_args = ['--repo', args.repo] if args.repo else []
        if args.dry_run:
            harvest_args.append('--dry-run')
        if args.product:
            harvest_args += ['--product', args.product]
        return harvest_main(harvest_args)
    if args.command == 'pr-hygiene':
        from asf.harvest.pr_hygiene import main as pr_hygiene_main
        pr_hygiene_args = ['--product', args.product] if args.product else []
        return pr_hygiene_main(pr_hygiene_args)
    if args.command == 'doctor':
        from asf.doctor import cmd_doctor
        return cmd_doctor(args, root)
    if args.command == 'tick':
        from asf.tick.tick import cmd_tick
        return cmd_tick(args)
    if args.command in ('roadmap', 'backlog', 'parity', 'prod', 'sessions', 'status', 'tokens'):
        view_root = resolve_record(args, announce=_announce_stderr if getattr(args, 'json', False) else print)
        if args.command == 'roadmap':
            from asf.views.roadmap import cmd_roadmap
            return cmd_roadmap(args, view_root)
        if args.command == 'backlog':
            from asf.views.board import cmd_backlog
            return cmd_backlog(args, view_root)
        if args.command == 'parity':
            from asf.views.parity import cmd_parity
            return cmd_parity(args, view_root)
        if args.command == 'prod':
            from asf.views.prod import cmd_prod
            return cmd_prod(args, view_root)
        if args.command == 'sessions':
            from asf.views.sessions import cmd_sessions
            return cmd_sessions(args, view_root)
        if args.command == 'tokens':
            from asf.views.tokens import cmd_tokens
            return cmd_tokens(args, view_root)
        if args.command == 'status':
            from asf.views.status import cmd_status
            return cmd_status(args, view_root)
    if args.command == 'capacity':
        from asf.views.capacity import cmd_capacity
        return cmd_capacity(args)
    if args.command == 'shadow-diff':
        from asf.tick.shadow_diff import cmd_shadow_diff
        return cmd_shadow_diff(args)
    if args.command == 'scheduler':
        from asf.scheduler import cmd_scheduler
        return cmd_scheduler(args, root)
    # commands registered with set_defaults(run=…) (init, schema-migrate, upgrade, hooks, hook)
    if getattr(args, 'run', None):
        return args.run(args)
    # commands registered with set_defaults(func=…) (next, workers …)
    if getattr(args, 'func', None):
        return args.func(args)

    parser.print_help()
    return 2


if __name__ == '__main__':
    sys.exit(main())
