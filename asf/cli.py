"""asf.cli — ``asf <command> [--product X]``.

Every record command resolves its record through :func:`resolve_record` (B-0050): the product's
``backlog_dir`` (``--product``, else ``$ASF_PRODUCT``, else ``default_product``), or the cwd only
when it *is* a record and no product resolves; the first line printed is ``record: <path>``. No
command creates anything under the cwd (``tests/test_path_resolution.py`` runs the whole table
from an empty directory). ``doctor`` and ``scheduler`` take the product, never the cwd.

The commands below are the week-1 fast-path set: today's record/tick/groom/rules tools, moved
behind product config. The fuller command surface (``init``, ``roadmap``, ``backlog``,
``product``, ``migrate-epic``, ...) lands with the 0.1 spec.
"""
import argparse
